include!("livekit.rs");

/// The `livekit.agent` protobuf package: `AgentSessionEvent`, `SessionRequest` and the agent
/// worker/inference messages. Generated by `generate_proto.sh`; a new package needs its own
/// `include!` or the types exist on disk and are reachable from nowhere.
pub mod agent {
    include!("livekit.agent.rs");

    /// The protocol default when an application omits its partition key.
    /// Frameworks resolve it before writing, since SQL requires an explicit key.
    pub const DEFAULT_PARTITION_KEY: &str = "default";

    /// The newest conversation schema a thread's database can hold (protocol's
    /// `livekit/agent/thread_schema.go`).
    pub const THREAD_SCHEMA_VERSION: i64 = 1;

    /// Version 1 of the conversation schema inside a thread's database, one statement per `;`
    /// (comments hold none).
    pub const THREAD_SCHEMA_V1: &str =
        include_str!("../protocol/livekit/agent/thread_schema_v1.sql");

    #[cfg(test)]
    mod tests {
        use super::*;
        use prost::Message as _;

        #[test]
        fn function_call_metadata_uses_field_seven_and_ignores_legacy_field_six() {
            let call = FunctionCall {
                extra: [
                    ("lk.approval".into(), "\"granted\"".into()),
                    ("lk.delegation.state".into(), "{\"pending_task_id\":\"task-1\"}".into()),
                ]
                .into(),
                ..Default::default()
            };
            let encoded = call.encode_to_vec();
            assert_eq!(encoded[0], 0x3a, "metadata belongs to length-delimited field 7");
            assert_eq!(FunctionCall::decode(encoded.as_slice()).unwrap().extra, call.extra);
            let legacy: &[u8] = &[0x32, 0x04, b't', b'u', b'r', b'n'];
            assert!(FunctionCall::decode(legacy).unwrap().extra.is_empty());
        }

        #[test]
        fn the_thread_schema_matches_protocol() {
            let go = include_str!("../protocol/livekit/agent/thread_schema.go");
            assert!(go.contains(&format!("const ThreadSchemaVersion = {THREAD_SCHEMA_VERSION}")));
            assert!(THREAD_SCHEMA_V1.contains("CREATE TABLE schema_version"));
            assert!(
                go.contains(&format!("const DefaultPartitionKey = \"{DEFAULT_PARTITION_KEY}\""))
            );
        }
    }
}

