//! Generates `../src/generated.rs` from `../openapi.yaml` with progenitor.
//!
//! The spec is OpenAPI 3.1 and progenitor reads 3.0 only, so it is first lowered to 3.0:
//! `type: [T, "null"]` becomes `nullable`, protojson int64 (`[integer, string]`) becomes a
//! string, `oneOf` arms of `type: "null"` or `not` are dropped, and 3.1-only keywords
//! (`examples`, `unevaluatedProperties`) are removed. `additionalProperties: false` is
//! dropped so a field added server side does not break the client, and so is the bodies' `title`.

use std::{env, fs};

use progenitor::{GenerationSettings, Generator, InterfaceStyle};
use serde_json::{json, Map, Value};

/// Spec schemas served by livekit-protocol types, keyed by typify's name for them.
const REPLACEMENTS: &[(&str, &str)] = &[
    ("LivekitAgentAgentThreadThread", "::livekit_protocol::agent::agent_thread::Thread"),
    ("LivekitAgentAgentThreadItem", "::livekit_protocol::agent::agent_thread::Item"),
    ("LivekitAgentAgentTaskTask", "::livekit_protocol::agent::agent_task::Task"),
    ("LivekitAgentAgentTaskStatus", "::livekit_protocol::agent::agent_task::Status"),
    ("LivekitAgentDbAgentDatabase", "::livekit_protocol::agent_db::AgentDatabase"),
    ("GoogleProtobufDuration", "::pbjson_types::Duration"),
    ("GoogleProtobufTimestamp", "::pbjson_types::Timestamp"),
];

fn main() {
    let dir = env::args().nth(1).expect("usage: generate <crate dir>");
    let yaml = fs::read_to_string(format!("{dir}/openapi.yaml")).unwrap();
    let mut spec: Value = serde_yaml::from_str(&yaml).unwrap();
    spec["openapi"] = json!("3.0.3");
    lower(&mut spec);
    untitle_bodies(&mut spec);
    let spec: openapiv3::OpenAPI = serde_json::from_value(spec).unwrap();

    let mut settings = GenerationSettings::new();
    settings
        .with_interface(InterfaceStyle::Positional)
        .with_inner_type(quote::quote!(crate::Credentials));
    for (name, path) in REPLACEMENTS {
        settings.with_replacement(name, path, std::iter::empty());
    }
    let tokens = Generator::new(&settings).generate_tokens(&spec).unwrap();
    let file = prettyplease::unparse(&syn::parse2(tokens).unwrap());
    let header = "// @generated by generate.sh from openapi.yaml. Do not edit.\n\n";
    fs::write(format!("{dir}/src/generated.rs"), format!("{header}{file}")).unwrap();
}

/// Inline request bodies are all titled `Request`, which typify would merge into one type;
/// untitled, each is named after its operation.
fn untitle_bodies(spec: &mut Value) {
    let paths = spec["paths"].as_object_mut().unwrap();
    for op in paths.values_mut().flat_map(|p| p.as_object_mut().unwrap().values_mut()) {
        if let Some(content) = op.pointer_mut("/requestBody/content") {
            for media in content.as_object_mut().unwrap().values_mut() {
                media["schema"].as_object_mut().unwrap().remove("title");
            }
        }
    }
}

fn lower(v: &mut Value) {
    match v {
        Value::Array(items) => items.iter_mut().for_each(lower),
        Value::Object(obj) => {
            obj.remove("examples");
            obj.remove("unevaluatedProperties");
            if obj.get("additionalProperties") == Some(&Value::Bool(false)) {
                obj.remove("additionalProperties");
            }
            lower_type(obj);
            for key in ["oneOf", "anyOf"] {
                lower_union(obj, key);
            }
            obj.values_mut().for_each(lower);
        }
        _ => {}
    }
}

fn lower_type(obj: &mut Map<String, Value>) {
    let Some(Value::Array(types)) = obj.get("type") else { return };
    let mut types: Vec<String> =
        types.iter().filter_map(Value::as_str).map(str::to_owned).collect();
    if types.iter().any(|t| t == "null") {
        types.retain(|t| t != "null");
        obj.insert("nullable".into(), json!(true));
    }
    let ty = match types.as_slice() {
        [t] => t.as_str(),
        _ if types.iter().any(|t| t == "string") => "string",
        _ => panic!("unsupported type union {types:?}"),
    };
    obj.insert("type".into(), json!(ty));
}

fn lower_union(obj: &mut Map<String, Value>, key: &str) {
    let Some(Value::Array(arms)) = obj.get_mut(key) else { return };
    let before = arms.len();
    arms.retain(|a| a.get("not").is_none() && a.get("type") != Some(&json!("null")));
    let nullable = arms.len() < before;
    if arms.iter().all(|a| a.as_object().is_some_and(|o| o.len() <= 2 && o.contains_key("type")))
        && arms.len() > 1
    {
        // google.protobuf.Value: any JSON value.
        obj.remove(key);
        obj.remove("type");
    } else if arms.len() == 1 {
        let arm = arms.pop().unwrap();
        obj.remove(key);
        obj.insert("allOf".into(), json!([arm]));
        if nullable {
            obj.insert("nullable".into(), json!(true));
        }
    }
}
